-- Run on an isolated PostgreSQL database after migration. Never on production.
begin;
create function pg_temp.denied(action text, payload jsonb, actor jsonb default '{}') returns void language plpgsql as $$
begin
  begin perform public.mes_dispatch(action,payload,actor);
  exception when others then return; end;
  raise exception 'Expected denial: %',action;
end $$;
do $$
declare
  owner jsonb := '{"owner":true,"uid":"owner-test","name":"MES Owner"}';
  user_id text; leader text; dept text; device jsonb; challenge jsonb; proof jsonb;
  result jsonb; issue text; session jsonb; token text; rows jsonb; i int; c int;
begin
  assert not has_function_privilege('anon','public.mes_dispatch(text,jsonb,jsonb)','EXECUTE');
  assert not has_function_privilege('authenticated','public.mes_dispatch(text,jsonb,jsonb)','EXECUTE');
  assert has_function_privilege('service_role','public.mes_dispatch(text,jsonb,jsonb)','EXECUTE');
  assert not has_schema_privilege('anon','mes_private','USAGE');
  assert (public.mes_dispatch('getDirectory','{}')->>'requiresWindows')::boolean;
  perform pg_temp.denied('getSession','{}');
  perform pg_temp.denied('read','{"path":"issues"}');
  perform pg_temp.denied('loginManagedUser','{"uid":"bogus"}');
  leader:=public.mes_dispatch('manageDirectory','{"type":"teamLeaders","operation":"create","name":"Leader"}',owner)->>'id';
  dept:=public.mes_dispatch('manageDirectory','{"type":"departments","operation":"create","name":"Assembly"}',owner)->>'id';
  user_id:=public.mes_dispatch('manageUser','{"operation":"create","username":"phtuan","displayName":"Tuan"}',owner)->>'uid';
  perform pg_temp.denied('manageUser','{"operation":"create","username":"phtuan","displayName":"Duplicate"}',owner);
  perform pg_temp.denied('manageUser','{"operation":"create","username":"a..b","displayName":"Invalid"}',owner);
  device:=public.mes_dispatch('registerDevice','{"label":"Test Windows"}',owner);
  assert device ? 'secret';
  assert not ((public.mes_dispatch('listDevices','{}',owner)->'devices'->0) ? 'secret');
  challenge:=public.mes_dispatch('startWindowsChallenge','{"username":"phtuan"}');
  perform pg_temp.denied('startWindowsChallenge','{"username":"phtuan"}');
  proof:=challenge||jsonb_build_object('deviceId',device->>'deviceId');
  proof:=proof||jsonb_build_object('signature',encode(extensions.hmac(convert_to((proof->>'challengeId')||E'\n'||(proof->>'nonce')||E'\n'||(proof->>'username')||E'\n'||(proof->>'deviceId'),'UTF8'),decode(device->>'secret','base64'),'sha256'),'hex'));
  perform pg_temp.denied('completeWindowsChallenge',proof||'{"username":"other"}');
  perform pg_temp.denied('completeWindowsChallenge',proof||'{"nonce":null}');
  token:=public.mes_dispatch('completeWindowsChallenge',proof)->>'sessionToken';
  perform pg_temp.denied('completeWindowsChallenge',proof);
  session:=jsonb_build_object('session',token);
  assert public.mes_dispatch('getSession','{}',session)->'user'->>'uid'=user_id;
  perform pg_temp.denied('read','{"path":"devices"}',session);
  perform pg_temp.denied('read','{"path":"users"}',session);
  perform pg_temp.denied('setPolicy','{"requiresWindows":false}',session);
  result:=jsonb_build_object('subject','MES error','process','Station 01','description','A detailed test feedback','reporterUid',user_id,'teamLeaderId',leader,'departmentId',dept);
  perform pg_temp.denied('createIssue',result||'{"subject":null}',session);
  perform pg_temp.denied('createIssue',result||'{"reporterUid":"other"}',session);
  result:=public.mes_dispatch('createIssue',result,session); issue:=result->>'id';
  assert jsonb_array_length(result->'uploadSlots')=5;
  assert jsonb_array_length(public.mes_dispatch('read','{"path":"issues"}',session)->'rows')=1;
  assert jsonb_array_length(public.mes_dispatch('readBundle','{"paths":[{"path":"issues"},{"path":"departments"}]}',session)->'snapshots'->'issues'->'rows')=1;
  perform pg_temp.denied('readBundle','{"paths":[{"path":"issues"},{"path":"devices"}]}',session);
  perform pg_temp.denied('updateIssue',jsonb_build_object('id',issue,'operation','handling','status','Resolved','priority','High'),session);
  perform pg_temp.denied('deleteIssue',jsonb_build_object('id',issue),session);
  perform pg_temp.denied('uploadUrl',jsonb_build_object('path','issues/'||issue||'/arbitrary'),session);
  perform public.mes_dispatch('uploadUrl',jsonb_build_object('path','issues/'||issue||'/'||(result->'uploadSlots'->>0)),session);
  perform public.mes_dispatch('attachFiles',jsonb_build_object('issueId',issue,'files',jsonb_build_array(jsonb_build_object('slot',result->'uploadSlots'->>0,'path','issues/'||issue||'/'||(result->'uploadSlots'->>0),'name','test.txt','size',12,'type','text/plain'))),session);
  perform public.mes_dispatch('downloadUrl',jsonb_build_object('path','issues/'||issue||'/'||(result->'uploadSlots'->>0)),session);
  perform public.mes_dispatch('updateIssue',jsonb_build_object('id',issue,'operation','handling','status','Resolved','priority','High','assessment','Fixed'),owner);
  perform public.mes_dispatch('updateIssue',jsonb_build_object('id',issue,'operation','edit','subject','Edited issue','process','Station 02','description','Updated detailed description'),owner);
  perform public.mes_dispatch('addComment',jsonb_build_object('issueId',issue,'text','Verified fix'),owner);
  rows:=public.mes_dispatch('read',jsonb_build_object('path','issues/'||issue||'/timeline','order','asc'),session)->'rows';
  assert jsonb_array_length(rows)=5;
  assert exists(select 1 from jsonb_array_elements(rows) e where e ? 'before' and e ? 'after');
  perform public.mes_dispatch('updateIssue',jsonb_build_object('id',issue,'operation','handling','status','In progress','priority','Medium'),owner);
  rows:=public.mes_dispatch('read','{"path":"issues"}',session)->'rows';
  assert not ((rows->0) ? 'resolvedAt');
  perform public.mes_dispatch('revokeDevice',jsonb_build_object('id',device->>'deviceId'),owner);
  perform pg_temp.denied('getSession','{}',session);
  perform pg_temp.denied('read','{"path":"issues"}',session);
  perform public.mes_dispatch('setPolicy','{"requiresWindows":false}',owner);
  token:=public.mes_dispatch('loginManagedUser',jsonb_build_object('uid',user_id))->>'sessionToken'; session:=jsonb_build_object('session',token);
  perform public.mes_dispatch('getSession','{}',session);
  perform public.mes_dispatch('manageUser',jsonb_build_object('operation','update','uid',user_id,'username','newname','displayName','Tuan'),owner);
  perform pg_temp.denied('getSession','{}',session);
  token:=public.mes_dispatch('loginManagedUser',jsonb_build_object('uid',user_id))->>'sessionToken'; session:=jsonb_build_object('session',token);
  perform public.mes_dispatch('logout','{}',session);
  perform pg_temp.denied('getSession','{}',session);
  token:=public.mes_dispatch('loginManagedUser',jsonb_build_object('uid',user_id))->>'sessionToken'; session:=jsonb_build_object('session',token);
  update mes_private.sessions set expires_at=now()-interval '1 second';
  perform pg_temp.denied('getSession','{}',session);
  perform public.mes_dispatch('manageUser',jsonb_build_object('operation','deactivate','uid',user_id,'active',false),owner);
  perform pg_temp.denied('loginManagedUser',jsonb_build_object('uid',user_id));
  perform public.mes_dispatch('deleteIssue',jsonb_build_object('id',issue),owner);
  perform public.mes_dispatch('finishDelete',jsonb_build_object('id',issue),owner);
  assert jsonb_array_length(public.mes_dispatch('read','{"path":"issues"}',owner)->'rows')=0;
  assert not exists(select 1 from mes_private.records where collection='issues/'||issue||'/timeline');
  raise notice 'PASS: grants, identity, proof tampering/replay, catalogs, issue workflow, attachments, audit, revocation, expiry, logout and deletion';
end $$;
rollback;
