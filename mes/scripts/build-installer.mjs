// One atomic SQL Editor installer, including upgrades for existing workspaces.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const migrations = new URL('supabase/migrations/', root);
const files = readdirSync(migrations).filter(f => f.endsWith('.sql')).sort();
const sections = files.map(file => {
  let sql = readFileSync(new URL(file, migrations), 'utf8');
  if (file === '202610150001_mes.sql') {
    sql = sql.replaceAll('create table mes_private.', 'create table if not exists mes_private.')
      .replace(`insert into mes_private.records values ('settings','policy','{"requiresWindows":true}');`, `insert into mes_private.records(collection,id,data) values ('settings','policy','{"requiresWindows":false}') on conflict(collection,id) do nothing;`);
  }
  return `-- SOURCE: ${file}\n${sql}`;
});
const content = `-- Generated by node mes/scripts/build-installer.mjs. Run the ENTIRE file in Supabase SQL Editor.\n-- Atomic and safe to rerun; keeps existing issues, profiles, passwords and attachments.\nBEGIN;\nSET LOCAL lock_timeout='15s';\n${sections.join('\n')}\nCOMMIT;\n-- First installation only: keep the activationCode PRIVATE. Existing owner is not reset.\nSELECT public.mes_issue_owner_activation() AS owner_activation;\n`;
writeFileSync(new URL('supabase/install-accounts.sql', root), content);
